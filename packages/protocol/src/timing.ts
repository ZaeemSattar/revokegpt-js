/**
 * Constant-time comparison over equal-length inputs (no early return on a differing byte).
 * Differing lengths return false immediately; lengths are not secret in our formats.
 */
export function timingSafeEqual(a: Uint8Array, b: Uint8Array): boolean {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) diff |= (a[i] as number) ^ (b[i] as number);
  return diff === 0;
}
